export const RAMSIS_MAKE = EQUIPMENT_REGISTER.filter(e => e.makeAtRamsis).map(e => e.id);

/** Equipment to be purchased from approved vendors */
export const VENDOR_PURCHASE = EQUIPMENT_REGISTER.filter(e => e.purchaseFromVendor).map(e => e.id);

/** Get register entry by tag */
export function getEquipment(tag: string): EquipmentRegisterEntry | undefined {
  return EQUIPMENT_REGISTER.find(e => e.id === tag);
}

/** Group register by category */
export function groupByCategory(): Record<string, EquipmentRegisterEntry[]> {
  return EQUIPMENT_REGISTER.reduce((acc, e) => {
    const key = e.category.toUpperCase();
    if (!acc[key]) acc[key] = [];
    acc[key].push(e);
    return acc;
  }, {} as Record<string, EquipmentRegisterEntry[]>);
}

/** Get make vs buy summary */
export function getMakeBuySummary(): { make: number; buy: number; total: number } {
  return {
    make: EQUIPMENT_REGISTER.filter(e => e.makeAtRamsis).length,
    buy: EQUIPMENT_REGISTER.filter(e => e.purchaseFromVendor).length,
    total: EQUIPMENT_REGISTER.length,
  };
}
